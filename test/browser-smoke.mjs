// Run after installing Playwright: PLAYWRIGHT_MODULE must point to its index.mjs.
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.APP_URL || 'http://127.0.0.1:8765');
await page.getByRole('heading',{name:'把每一道题，练成你的底气。'}).waitFor();
await page.locator('[data-region="通用"]').click();
await page.locator('[data-action="start"]').click();
await page.locator('[data-option="A"]').click();
await page.locator('[data-action="submit"]').click();
await page.getByText('这道题再巩固一下').waitFor();
await page.reload();
await page.locator('[data-action="resume"]').click();
await page.getByText('这道题再巩固一下').waitFor();
await page.locator('[data-action="favorite"]').click();
await page.locator('[data-action="finish"]').click();
await page.getByText('本轮练习已完成').waitFor();
await page.getByRole('button',{name:'错题收藏',exact:true}).click();
await page.locator('#filter-bank').selectOption('');
await page.locator('.review-item h3').filter({hasText:'《大教学论》'}).waitFor();
await page.getByRole('button',{name:'模拟考试',exact:true}).click();
await page.locator('[data-action="start"]').click();
await page.locator('[data-option="B"]').click();
assert.equal(await page.locator('.explanation').count(),0);
page.once('dialog',d=>d.accept());
await page.locator('[data-action="finish"]').click();
await page.getByText('模拟考试已交卷').waitFor();
await page.getByRole('button',{name:'导入备份',exact:true}).click();
await page.locator('#bank-name').fill('浏览器测试题库');
await page.locator('#bank-province').selectOption('广东');
await page.locator('#import-text').fill(JSON.stringify({questions:[{text:'浏览器导入示例',options:['A.甲','B.乙'],answer:'B',explanation:'核对用解析'}]}));
await page.locator('[data-action="preview-import"]').click();
await page.locator('[data-action="confirm-import"]').click();
await page.getByRole('button',{name:'开始练习',exact:true}).click();
await page.locator('#filter-bank').selectOption({label:'浏览器测试题库'});
await page.locator('[data-action="start"]').click();
await page.getByText('浏览器导入示例',{exact:true}).waitFor();
for(const width of [390,760,1440]) {
 await page.setViewportSize({width,height:900});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 assert.equal(overflow,false,`no overflow at ${width}px`);
}
// Full backup survives a fresh browser storage origin/context.
await page.getByRole('button',{name:'导入备份',exact:true}).click();
const [backupDownload]=await Promise.all([page.waitForEvent('download'),page.locator('[data-action="backup"]').click()]);
const stream=await backupDownload.createReadStream();const chunks=[];for await(const chunk of stream)chunks.push(chunk);
const backup=Buffer.concat(chunks);
const context2=await browser.newContext({viewport:{width:390,height:844}});const restored=await context2.newPage();
await restored.goto(process.env.APP_URL || 'http://127.0.0.1:8765');
await restored.getByRole('button',{name:'导入备份',exact:true}).click();
restored.once('dialog',d=>d.accept());
await restored.locator('#backup-file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:backup});
await restored.getByText('备份已恢复。',{exact:true}).waitFor();
await restored.getByRole('button',{name:'开始练习',exact:true}).click();
await restored.locator('[data-action="resume"]').click();
await restored.getByText('浏览器导入示例',{exact:true}).waitFor();
// A countdown is persisted and expiration hands in the exam exactly once.
await restored.getByRole('button',{name:'模拟考试',exact:true}).click();
restored.once('dialog',d=>d.accept());
await restored.locator('[data-action="start"]').click();
await restored.evaluate(()=>{const key='jiaozong-practice-state';const s=JSON.parse(localStorage.getItem(key));s.session.deadline=Date.now()-1000;localStorage.setItem(key,JSON.stringify(s));});
await restored.reload();
await restored.locator('[data-action="resume"]').click();
await restored.getByText('模拟考试已交卷',{exact:true}).waitFor();
assert.deepEqual(errors,[]);
console.log('PASS: desktop/mobile, practice, refresh, wrong book, favorites, exam, import, backup restore and automatic timed hand-in');
await browser.close();
